/* =========================================================
   CURRENT LANGUAGE
========================================================= */

let currentLanguage =
  localStorage.getItem(
    "portfolio-language"
  ) || "en";



/* =========================================================
   TRANSLATE FUNCTION
========================================================= */

function t(key) {

  return (
    TRANSLATIONS[currentLanguage]?.[key]
    ||
    TRANSLATIONS.en?.[key]
    ||
    key
  );

}



/* =========================================================
   APPLY LANGUAGE
========================================================= */

function applyLanguage(language) {

  if (
    !TRANSLATIONS[language]
  ) {
    language = "en";
  }


  currentLanguage =
    language;


  localStorage.setItem(
    "portfolio-language",
    language
  );


  document.documentElement.lang =
    language === "zh"
      ? "zh-CN"
      : "en";


  /* NORMAL TEXT */

  document
    .querySelectorAll(
      "[data-i18n]"
    )
    .forEach(
      element => {

        const key =
          element.dataset.i18n;


        const translated =
          TRANSLATIONS[
            language
          ]?.[key];


        if (
          translated !== undefined
        ) {

          element.textContent =
            translated;

        }

      }
    );


  /* PLACEHOLDERS */

  document
    .querySelectorAll(
      "[data-i18n-placeholder]"
    )
    .forEach(
      element => {

        const key =
          element.dataset
            .i18nPlaceholder;


        const translated =
          TRANSLATIONS[
            language
          ]?.[key];


        if (translated) {

          element.placeholder =
            translated;

        }

      }
    );


  /* LANGUAGE BUTTON */

  const button =
    document.getElementById(
      "language-toggle"
    );


  if (button) {

    button.textContent =
      language === "en"
        ? "中文"
        : "EN";

  }


  /*
    Tell dynamic sections
    such as Journey/Travel
    that language changed.
  */

  window.dispatchEvent(
    new CustomEvent(
      "portfolio-language-change",
      {
        detail: {
          language
        }
      }
    )
  );

}



/* =========================================================
   LANGUAGE BUTTON
========================================================= */

function setupLanguageButton() {

  const button =
    document.getElementById(
      "language-toggle"
    );


  if (!button) {
    return;
  }


  button.addEventListener(
    "click",
    () => {

      const nextLanguage =
        currentLanguage === "en"
          ? "zh"
          : "en";


      applyLanguage(
        nextLanguage
      );


      /*
        Optional:
        use sound system from main site
        if function exists.
      */

      if (
        typeof window
          .playClickSound
        === "function"
      ) {

        window.playClickSound();

      }

    }
  );

}



/* =========================================================
   INITIALIZE
========================================================= */

document.addEventListener(
  "DOMContentLoaded",
  () => {

    setupLanguageButton();

    applyLanguage(
      currentLanguage
    );

  }
);


/* Make helper accessible
   to other page scripts */

window.t = t;

window.applyLanguage =
  applyLanguage;

window.TRANSLATIONS =
  TRANSLATIONS;